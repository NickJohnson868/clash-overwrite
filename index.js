function registerServices(config) {
  for (const svc of SERVICE_DEFINITIONS) {
    if (!ruleOptions[svc.key]) {
      continue;
    }

    if (Array.isArray(svc.rules)) {
      rules.push(...svc.rules);
    } else {
      rules.push(svc.rules);
    }

    if (svc.ruleProvider) {
      ruleProviders.set(
        svc.ruleProvider.key,
        {
          ...ruleProviderDefaults,
          ...svc.ruleProvider.config,
        }
      );
    }

    const proxies =
      typeof svc.proxies === "function"
        ? svc.proxies()
        : svc.proxies || getDefaultProxies();

    config["proxy-groups"].push({
      ...proxyGroupDefaults,
      name: svc.name,
      type: "select",
      proxies,
      ...(svc.url && {
        url: svc.url
      }),
      ...(svc.icon && {
        icon: svc.icon
      }),
    });
  }
}

